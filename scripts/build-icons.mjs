// Builds src/icons/icons.ts from Tabler outline icons (MIT): only the icons the app uses.
import { readFileSync, writeFileSync } from 'node:fs';
const names = ['bulb','pencil','hammer','check','lock','player-play','loader','alert-triangle','search','x','sun','moon','device-desktop',
 'arrow-left','arrow-right','link','copy','plus','flag','message-circle','user','user-minus','trash','arrow-back-up','chevron-up','chevron-down',
 'help','logout','settings','list','layout-grid','box','external-link','upload','download','circle','refresh','eye','cloud-off','cloud-check'];
const out = {};
for (const n of names) {
  const s = readFileSync(`node_modules/@tabler/icons/icons/outline/${n}.svg`, 'utf8');
  out[n] = [...s.matchAll(/<(path|circle|rect|line|polyline)([^>]*)\/>/g)]
    .map(([, tag, attrs]) => ({ tag, a: Object.fromEntries([...attrs.matchAll(/([\w-]+)="([^"]*)"/g)].map((m) => [m[1], m[2]])) }))
    .filter((e) => !(e.a.stroke === 'none' && e.a.d === 'M0 0h24v24H0z'));
}
writeFileSync('src/icons/icons.ts', '// GENERATED by scripts/build-icons.mjs from @tabler/icons (MIT). Do not edit.\n' +
  `export const ICONS: Record<string, { tag: string; a: Record<string, string> }[]> = ${JSON.stringify(out)};\n`);
console.log('icons:', names.length);
